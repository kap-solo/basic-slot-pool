import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function resolveCommit() {
  const renderCommit = process.env.RENDER_GIT_COMMIT?.trim();
  if (renderCommit) {
    return renderCommit.slice(0, 7);
  }

  try {
    return execSync('git rev-parse --short HEAD', {
      cwd: root,
      encoding: 'utf8',
    }).trim();
  } catch {
    return 'dev';
  }
}

const commit = resolveCommit();
const outPath = join(root, 'js', 'build-info.js');

writeFileSync(
  outPath,
  `/** Generated by scripts/write-build-info.mjs — do not edit. */\nexport const BUILD_COMMIT = '${commit}';\n`,
);

console.log(`build-info: ${commit}`);
