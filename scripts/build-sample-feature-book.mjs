/**
 * Build hand-tuned sample feature book for dev playback.
 * Run: node scripts/build-sample-feature-book.mjs
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { simulateFeatureBook } from '../math/feature.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../js/featureSampleBook.js');

/** Seeds chosen so feature total ≈ 16× (1600 cents @ $1 bet). */
const SEED = 20;
const FREE_SPIN_SEEDS = [20, 9993, 19966, 29939, 39912, 49885, 59858, 69831];

const book = simulateFeatureBook(SEED, { freeSpinSeeds: FREE_SPIN_SEEDS, bookId: 9001 });

const body = `/**
 * Dev sample — 3 scatters + 8 free spins (~${(book.payoutMultiplier / 100).toFixed(2)}×).
 * Generated by scripts/build-sample-feature-book.mjs — do not hand-edit.
 */
export const SAMPLE_FEATURE_BOOK = ${JSON.stringify(book, null, 2)};
`;

writeFileSync(outPath, body, 'utf8');

console.log(`Wrote ${outPath}`);
console.log(`  payoutMultiplier (cents): ${book.payoutMultiplier}`);
console.log(`  featureMultiplier: ${book.featureMultiplier}`);
console.log(`  events: ${book.events.length}`);
